/** Bounded read policy for the browser client (#411).
 *
 * These are budgets for waiting for response headers, not promises that a
 * server-side operation will finish in that time.  The long class is for
 * explicitly expensive reads such as search and history; an idle SSE body is
 * never put under one of these timers.
 */
export type OpClass = "auth" | "metadata" | "list" | "detail" | "long";

/** Documented client-side response-header deadlines by operation class. */
export const DEADLINE_MS: Readonly<Record<OpClass, number>> = {
  auth: 4_000,
  metadata: 4_000,
  list: 8_000,
  detail: 8_000,
  long: 30_000,
};

export interface DeadlineHandle {
  /** The composed signal passed to the request. */
  signal: AbortSignal;
  /** Stop the timer and detach the upstream listener after the request settles. */
  cancel: () => void;
}

function abortError(message: string): DOMException {
  return new DOMException(message, "AbortError");
}

/** True for the deliberate timeout generated by this module. */
export function isTimeoutReason(reason: unknown): boolean {
  return (reason as { name?: unknown } | null)?.name === "TimeoutError";
}

/**
 * Compose an operation deadline with an optional caller cancellation signal.
 * This is intentionally hand-rolled: it works with the older WebKit used by
 * the Capacitor shell and is deterministic under Vitest fake timers.
 */
export function deadline(
  cls: OpClass,
  upstream?: AbortSignal,
): DeadlineHandle {
  return deadlineFor(DEADLINE_MS[cls], upstream);
}

/** Numeric form used by the transport's per-attempt retry option. */
export function deadlineFor(
  timeoutMs: number,
  upstream?: AbortSignal,
): DeadlineHandle {
  const controller = new AbortController();
  let timer: ReturnType<typeof setTimeout> | null = setTimeout(() => {
    controller.abort(
      new DOMException(
        `request exceeded its ${timeoutMs}ms deadline`,
        "TimeoutError",
      ),
    );
  }, timeoutMs);

  const onUpstreamAbort = () => {
    controller.abort(
      upstream?.reason ?? abortError("The request was cancelled."),
    );
  };
  if (upstream) {
    if (upstream.aborted) onUpstreamAbort();
    else upstream.addEventListener("abort", onUpstreamAbort, { once: true });
  }

  return {
    signal: controller.signal,
    cancel: () => {
      if (timer !== null) {
        clearTimeout(timer);
        timer = null;
      }
      upstream?.removeEventListener("abort", onUpstreamAbort);
    },
  };
}
